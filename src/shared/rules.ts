export const TRACK_RULES = {
  FIRST_WAVE_DISTANCE: 10,
  /** Every BREATHER_EVERY meters, a stretch of BREATHER_LENGTH meters with only pickups. */
  BREATHER_EVERY: 700,
  BREATHER_LENGTH: 45,
  BREATHER_SPACING: 15,
  /**
   * Minimum meters between two barrier waves to be able to change lanes, at the worst
   * case (max speed 250 → 25 m/s): lane change 140px / 310px/s = 0.45s + 0.25s reaction.
   */
  SAFE_GAP_ONE_LANE: 18,
  /** Same for crossing two lanes: 280px / 310px/s = 0.9s + 0.25s reaction. */
  SAFE_GAP_TWO_LANES: 29
} as const;

export function getDifficultyPhase(distance: number): DifficultyPhase {
  let phase = DIFFICULTY_PHASES[0];
  for (const p of DIFFICULTY_PHASES) {
    if (distance >= p.fromDistance) phase = p;
  }
  return phase;
}

export function isBreatherStretch(distance: number): boolean {
  return (
    distance >= TRACK_RULES.BREATHER_EVERY &&
    distance % TRACK_RULES.BREATHER_EVERY < TRACK_RULES.BREATHER_LENGTH
  );
}

/**
 * Evaluates collision damage considering active flank shields.
 * Shield absorption negates 100% of damage on the corresponding side if active.
 */
export function computeCollisionDamage(
  sideThreat: 'left' | 'right' | undefined,
  activeShields: { left: boolean; right: boolean }
): { damage: number; deflected: boolean } {
  if (sideThreat === 'left' && activeShields.left) {
    return { damage: 0, deflected: true };
  }
  if (sideThreat === 'right' && activeShields.right) {
    return { damage: 0, deflected: true };
  }
  if (sideThreat === undefined && activeShields.left && activeShields.right) {
    // Dual front barrier deflection when both flank shields are synchronized
    return { damage: 0, deflected: true };
  }
  return {
    damage: GAMEPLAY_CONSTANTS.OBSTACLE_COLLISION_DAMAGE,
    deflected: false
  };
}
